// ---- downloads (mg_download.hpp): the catalogue, and the queue the worker takes .dljob files from
static const std::vector<mg::ModelFile> & catalog() {
    static const std::vector<mg::ModelFile> c = [] {
        std::string err;
        return mg::parse_catalog(std::string(reinterpret_cast<const char *>(mg_models_txt), mg_models_txt_len), err);
    }();
    return c;
}
static std::string group_title(const std::string & g) { return g == "text-qwen35-9b" ? "IA de texto (Qwen3.5 9B)" : g; }
static std::string group_use(const std::string &) { return "text"; }
static std::vector<nlohmann::json> download_states() {
    std::vector<nlohmann::json> out;
    if (DIR * d = opendir(kMgDownloads)) {
        while (dirent * e = readdir(d)) {
            const std::string n = e->d_name;
            if (n.size() < 6 || n.compare(n.size() - 5, 5, ".json") != 0) continue;
            auto j = nlohmann::json::parse(slurp(std::string(kMgDownloads) + "/" + n), nullptr, false);
            if (j.is_object()) out.push_back(j);
        }
        closedir(d);
    }
    std::sort(out.begin(), out.end(), [](const nlohmann::json & a, const nlohmann::json & b) { return a.value("id", "") > b.value("id", ""); });
    return out;
}
static void save_download_state(const nlohmann::json & j) {
    mkdir(kMgDownloads, 0777);
    const std::string p = std::string(kMgDownloads) + "/" + j.value("id", "x") + ".json";
    { std::ofstream f(p + ".tmp"); f << j.dump(); }
    rename((p + ".tmp").c_str(), p.c_str());
}

// The text model the worker would load ("" when none): PAUL3D's models/text, then PS5LM's models.
static std::vector<std::string> text_dirs() { return {std::string(kMgDir) + "/models/text", "/data/PS5LM/models"}; }
static std::string text_model() { return mg::find_text_model(text_dirs()); }

// A text request onto the queue: (202, {"id"}) or (4xx, {"error"}).
static std::pair<int, std::string> queue_text(const std::string & body) {
    mg::TextJob job;
    std::string err;
    if (!mg::parse_text_job(body, job, err)) return {400, nlohmann::json{{"error", err}}.dump()};
    if (text_model().empty()) return {409, "{\"error\":\"missing_model\"}"};
    if (!job.model.empty() && mg::resolve_text_model(text_dirs(), job.model).empty()) return {404, nlohmann::json{{"error", "no such model: " + job.model}}.dump()};
    static std::atomic<int> counter{0};
    char stamp[32];
    const time_t now = time(nullptr);
    std::strftime(stamp, sizeof stamp, "%Y%m%d-%H%M%S", std::localtime(&now));
    const std::string id = std::string("t") + stamp + "-" + std::to_string(counter++);
    mkdir(kMgText, 0777);
    const std::string base = std::string(kMgJobs) + "/" + id;
    { std::ofstream f(base + ".textjob.tmp", std::ios::binary); f << body; }
    rename((base + ".textjob.tmp").c_str(), (base + ".textjob").c_str());
    return {202, "{\"id\":\"" + id + "\"}"};
}

void mg_web_run(int port) {
    mkdir(kMgIn, 0777);
    mkdir(kMgOut, 0777);
    mkdir(kMgJobs, 0777);
    httplib::Server svr;
    svr.set_payload_max_length(64u << 20);
    // No Access-Control-Allow-Origin: a page of another site, open in a browser on your network, must not be able to
    // read from or drive the console. The web interface is served by the console itself, so it is same-origin.
    svr.set_post_routing_handler([](const httplib::Request &, httplib::Response & res) {
        res.set_header("Cache-Control", "no-store");
        res.set_header("X-Content-Type-Options", "nosniff");
    });
    svr.set_pre_routing_handler([](const httplib::Request & req, httplib::Response & res) {
        auto refuse = [&](int code, const char * msg) {
            res.status = code;
            res.set_content(std::string("{\"error\":\"") + msg + "\"}", "application/json");
            return httplib::Server::HandlerResponse::Handled;
        };
        // A POST has to come from this page: if the browser names an origin, it is the console's own address.
        if (req.method == "POST") {
            const std::string origin = req.get_header_value("Origin");
            if (!origin.empty() && origin.find("//" + req.get_header_value("Host")) == std::string::npos) return refuse(403, "cross-site request");
        }
        const bool api = req.path.rfind("/api/", 0) == 0 || req.path.rfind("/v1/", 0) == 0;  // /v1/: OpenAI's routes
        if (api && req.path != "/api/auth" && req.path != "/api/login") {
            if (!authorized(req, access_key())) {
                usleep(400000);  // a wrong key costs time
                return refuse(401, "key required");
            }
        }
        return httplib::Server::HandlerResponse::Unhandled;
    });
    svr.Get("/api/auth", [](const httplib::Request & req, httplib::Response & res) {
        const std::string key = access_key();
        res.set_content(std::string("{\"required\":") + (key.empty() ? "false" : "true") + ",\"ok\":" +
                            (authorized(req, key) ? "true" : "false") + "}",
                        "application/json");
    });
    svr.Post("/api/login", [](const httplib::Request & req, httplib::Response & res) {
        const std::string key = access_key();
        if (!key.empty() && !same(field(req, "key", ""), key)) {
            usleep(400000);
            res.status = 401;
            res.set_content("{\"error\":\"wrong key\"}", "application/json");
            return;
        }
        if (!key.empty()) res.set_header("Set-Cookie", "mgkey=" + to_hex(key) + "; Path=/; HttpOnly; SameSite=Strict; Max-Age=2592000");
        res.set_content("{\"ok\":true}", "application/json");
    });
    // The page: a part from a sentence (the console's language model writes OpenSCAD, the browser makes the STL).
    // /cad is where it was before 0.7.0.
    auto page = [](const httplib::Request &, httplib::Response & res) {
        res.set_content(reinterpret_cast<const char *>(mg_cad_html), mg_cad_html_len, "text/html; charset=utf-8");
    };
    svr.Get("/", page);
    svr.Get("/cad", page);
    svr.Get("/api/status", [](const httplib::Request &, httplib::Response & res) {
        res.set_content(status_json(), "application/json");
    });
    // ---- models the title downloads itself
    svr.Get("/api/catalog", [](const httplib::Request &, httplib::Response & res) {
        nlohmann::json groups = nlohmann::json::array();
        for (const auto & g : mg::catalog_state(catalog(), kMgDir)) {
            std::string licence;
            for (const auto & f : catalog()) if (f.group == g.group) { licence = f.licence; break; }
            groups.push_back({{"group", g.group}, {"title", group_title(g.group)}, {"size", g.total}, {"have", g.have},
                              {"installed", g.installed}, {"licence", licence}, {"needed_for", group_use(g.group)}});
        }
        nlohmann::json names = nlohmann::json::array();
        for (const auto & m : mg::list_text_models(text_dirs())) names.push_back(m.name);
        const std::string def = text_model();
        res.set_content(nlohmann::json{{"groups", groups}, {"free", mg::free_bytes(kMgDir)}, {"text_models", names},
                                       {"text_default", def.empty() ? "" : def.substr(def.find_last_of('/') + 1)}}.dump(), "application/json");
    });
    svr.Post("/api/downloads", [](const httplib::Request & req, httplib::Response & res) {
        auto fail = [&](int code, const std::string & msg) { res.status = code; res.set_content(nlohmann::json{{"error", msg}}.dump(), "application/json"); };
        const auto body = nlohmann::json::parse(req.body, nullptr, false);
        if (!body.is_object() || !body.contains("group") || !body["group"].is_string()) return fail(400, "group is missing");
        if (body.value("accept_license", false) != true) return fail(400, "accept_license must be true: read the licence first");
        const std::string group = body["group"];
        int64_t total = 0;
        for (const auto & f : catalog()) if (f.group == group) total += f.size;
        if (total == 0) return fail(404, "no such group");
        for (const auto & g : mg::catalog_state(catalog(), kMgDir)) if (g.group == group && g.installed) return fail(409, "installed");
        for (const auto & d : download_states()) {
            const std::string st = d.value("state", "");
            if (d.value("group", "") == group && (st == "queued" || st == "downloading" || st == "verifying")) return fail(409, "already queued");
        }
        static std::atomic<int> counter{0};
        char stamp[32];
        const time_t now = time(nullptr);
        std::strftime(stamp, sizeof stamp, "%Y%m%d-%H%M%S", std::localtime(&now));
        const std::string id = std::string("d") + stamp + "-" + std::to_string(counter++);
        save_download_state({{"id", id}, {"group", group}, {"title", group_title(group)}, {"state", "queued"}, {"done", 0}, {"total", total}, {"speed", 0}});
        const std::string base = std::string(kMgJobs) + "/" + id;
        { std::ofstream f(base + ".dljob.tmp"); f << nlohmann::json{{"group", group}}.dump(); }
        rename((base + ".dljob.tmp").c_str(), (base + ".dljob").c_str());
        res.status = 202;
        res.set_content(nlohmann::json{{"id", id}}.dump(), "application/json");
    });
    svr.Get("/api/downloads", [](const httplib::Request &, httplib::Response & res) {
        res.set_content(nlohmann::json(download_states()).dump(), "application/json");
    });
    svr.Post(R"(/api/downloads/([A-Za-z0-9_-]+)/cancel)", [](const httplib::Request & req, httplib::Response & res) {
        const std::string id = req.matches[1].str();
        auto j = nlohmann::json::parse(slurp(std::string(kMgDownloads) + "/" + id + ".json"), nullptr, false);
        if (!j.is_object()) { res.status = 404; res.set_content("{\"error\":\"no such download\"}", "application/json"); return; }
        const std::string st = j.value("state", "");
        if (st == "queued" && unlink((std::string(kMgJobs) + "/" + id + ".dljob").c_str()) == 0) {
            j["state"] = "cancelled";
            save_download_state(j);
        } else if (st == "queued" || st == "downloading" || st == "verifying") {
            std::ofstream(std::string(kMgDownloads) + "/" + id + ".cancel") << "1";  // the worker stops at its next piece
        } else {
            res.status = 409; res.set_content("{\"error\":\"not running\"}", "application/json"); return;
        }
        res.set_content("{\"ok\":true}", "application/json");
    });

    // ---- text: the worker's text mode answers (mg_main.cpp, mg_textjob.hpp)
    svr.Post("/api/text", [](const httplib::Request & req, httplib::Response & res) {
        const auto r = queue_text(req.body);
        res.status = r.first;
        res.set_content(r.second, "application/json");
    });
    svr.Get(R"(/api/text/([A-Za-z0-9_-]+))", [](const httplib::Request & req, httplib::Response & res) {
        const std::string s = mg::text_status(kMgJobs, kMgText, req.matches[1].str());
        if (s.empty()) { res.status = 404; res.set_content("{\"error\":\"no such text request\"}", "application/json"); return; }
        res.set_content(s, "application/json");
    });
    svr.Get("/v1/models", [](const httplib::Request &, httplib::Response & res) {
        nlohmann::json j = {{"object", "list"}, {"data", nlohmann::json::array()}};
        for (const auto & m : mg::list_text_models(text_dirs())) j["data"].push_back({{"id", m.name}, {"object", "model"}});
        res.set_content(j.dump(), "application/json");
    });
    // OpenAI's chat completions for other programs: queued like /api/text, answered when the text is done (no
    // streaming of pieces; with "stream" the whole answer comes as one event).
    svr.Post("/v1/chat/completions", [](const httplib::Request & req, httplib::Response & res) {
        // OpenAI clients name a model of their own ("gpt-4o"): only an installed one is kept, else the default.
        std::string body = req.body;
        auto bj = nlohmann::json::parse(body, nullptr, false);
        if (bj.is_object() && bj.contains("model") && (!bj["model"].is_string() || mg::resolve_text_model(text_dirs(), bj["model"].get<std::string>()).empty())) {
            bj.erase("model");
            body = bj.dump();
        }
        const auto r = queue_text(body);
        auto oai_error = [&](int code, const std::string & msg) {
            res.status = code;
            res.set_content(nlohmann::json{{"error", {{"message", msg}, {"type", msg == "missing_model" ? "missing_model" : "invalid_request_error"}}}}.dump(), "application/json");
        };
        if (r.first != 202) {
            const auto e = nlohmann::json::parse(r.second, nullptr, false);
            return oai_error(r.first, e.is_object() && e.contains("error") ? e["error"].get<std::string>() : "error");
        }
        const std::string id = nlohmann::json::parse(r.second)["id"];
        nlohmann::json st;
        for (int i = 0; i < 3000; i++) {  // 600 s
            st = nlohmann::json::parse(mg::text_status(kMgJobs, kMgText, id), nullptr, false);
            if (st.is_object() && (st["status"] == "done" || st["status"] == "failed")) break;
            usleep(200000);
        }
        if (!st.is_object() || st["status"] != "done") return oai_error(504, st.is_object() && st.contains("error") ? st["error"].get<std::string>() : "timeout");
        std::string model = text_model().substr(text_model().find_last_of('/') + 1);
        if (bj.is_object() && bj.contains("model")) model = bj["model"];
        const std::string text = st["text"];
        if (bj.is_object() && bj.value("stream", false)) {
            nlohmann::json chunk = {{"id", id}, {"object", "chat.completion.chunk"}, {"model", model},
                                    {"choices", {{{"index", 0}, {"delta", {{"role", "assistant"}, {"content", text}}}, {"finish_reason", "stop"}}}}};
            res.set_content("data: " + chunk.dump() + "\n\ndata: [DONE]\n\n", "text/event-stream");
            return;
        }
        nlohmann::json out = {{"id", id}, {"object", "chat.completion"}, {"model", model},
                              {"choices", {{{"index", 0}, {"message", {{"role", "assistant"}, {"content", text}}}, {"finish_reason", "stop"}}}}};
        res.set_content(out.dump(), "application/json");
    });
    svr.Post("/api/quit", [](const httplib::Request &, httplib::Response & res) {
        std::ofstream(std::string(kMgDir) + "/quit") << "1";
        res.set_content("{\"ok\":true}", "application/json");
    });
    std::printf("paul3d: web interface on port %d\n", port);
    if (!svr.listen("0.0.0.0", port)) std::printf("paul3d: the web server could not listen on port %d\n", port);
}
