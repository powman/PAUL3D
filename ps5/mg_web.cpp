std::string esc(const std::string & s) {
    std::string o;
    for (char c : s) {
        switch (c) {
            case '"': o += "\\\""; break;
            case '\\': o += "\\\\"; break;
            case '\n': o += "\\n"; break;
            case '\r': break;
            case '\t': o += ' '; break;
            default:
                if (static_cast<unsigned char>(c) >= 0x20) o += c;
        }
    }
    return o;
}

bool exists(const std::string & p) {
    struct stat st;
    return stat(p.c_str(), &st) == 0;
}

long fsize(const std::string & p) {
    struct stat st;
    return stat(p.c_str(), &st) == 0 ? static_cast<long>(st.st_size) : -1;
}

std::string slurp(const std::string & p) {
    std::ifstream f(p, std::ios::binary);
    std::stringstream ss;
    ss << f.rdbuf();
    return ss.str();
}

std::vector<std::string> list_dir(const std::string & d) {
    std::vector<std::string> v;
    if (DIR * h = opendir(d.c_str())) {
        while (dirent * e = readdir(h)) {
            if (e->d_name[0] != '.') v.push_back(e->d_name);
        }
        closedir(h);
    }
    std::sort(v.begin(), v.end());
    return v;
}

bool ends_with(const std::string & s, const std::string & x) {
    return s.size() >= x.size() && s.compare(s.size() - x.size(), x.size(), x) == 0;
}

// Only [A-Za-z0-9_-]: ids are file names.
bool safe_id(const std::string & id) {
    if (id.empty() || id.size() > 80) return false;
    for (char c : id) {
        if (!isalnum(static_cast<unsigned char>(c)) && c != '_' && c != '-') return false;
    }
    return true;
}

// A form field: multipart (curl -F, the page) or url-encoded (curl -d) or in the query string.
std::string field(const httplib::Request & req, const char * name, const std::string & def) {
    if (req.has_file(name)) return req.get_file_value(name).content;
    if (req.has_param(name)) return req.get_param_value(name);
    return def;
}

std::string status_json() {
    std::lock_guard<std::mutex> lk(g_mg.mu);
    std::string o = "{\"busy\":" + std::string(g_mg.job.empty() ? "false" : "true");
    o += ",\"job\":\"" + esc(g_mg.job) + "\",\"stage\":\"" + esc(g_mg.stage) + "\",\"progress\":\"" + esc(g_mg.progress) + "\"";
    o += ",\"elapsed\":" + std::to_string(g_mg.job.empty() ? 0.0 : mg_now() - g_mg.job_t0);
    o += ",\"pool_free_gib\":" + std::to_string(g_mg.pool_free_gib) + ",\"pool_gib\":" + std::to_string(g_mg.pool_gib);
    o += ",\"threads\":" + std::to_string(g_mg.threads) + ",\"tail\":[";
    const size_t from = g_mg.tail.size() > 25 ? g_mg.tail.size() - 25 : 0;
    for (size_t i = from; i < g_mg.tail.size(); i++) o += (i > from ? ",\"" : "\"") + esc(g_mg.tail[i]) + "\"";
    return o + "]}";
}

// ---- access: an optional key in /data/PAUL3D/api-key.txt (one line). No file, or an empty one: open, as before. ----
std::string access_key() {
    std::string k = slurp(std::string(kMgDir) + "/api-key.txt");
    while (!k.empty() && (k.back() == '\n' || k.back() == '\r' || k.back() == ' ')) k.pop_back();
    return k;
}

std::string to_hex(const std::string & s) {
    static const char * digits = "0123456789abcdef";
    std::string         o;
    for (unsigned char c : s) {
        o += digits[c >> 4];
        o += digits[c & 15];
    }
    return o;
}

// No early exit at the first difference.
bool same(const std::string & a, const std::string & b) {
    unsigned char diff = a.size() != b.size();
    for (size_t i = 0; i < a.size() && i < b.size(); i++) diff |= static_cast<unsigned char>(a[i] ^ b[i]);
    return diff == 0;
}

std::string cookie_value(const httplib::Request & req, const std::string & name) {
    const std::string h   = req.get_header_value("Cookie");
    const std::string key = name + "=";
    size_t            p   = 0;
    while (p < h.size()) {
        while (p < h.size() && (h[p] == ' ' || h[p] == ';')) p++;
        if (h.compare(p, key.size(), key) == 0) {
            const size_t e = h.find(';', p);
            return h.substr(p + key.size(), e == std::string::npos ? std::string::npos : e - p - key.size());
        }
        p = h.find(';', p);
        if (p == std::string::npos) break;
    }
    return {};
}

// The key in an Authorization: Bearer header (scripts) or in the cookie the page gets at login (pictures and downloads).
bool authorized(const httplib::Request & req, const std::string & key) {
    if (key.empty()) return true;
    const std::string bearer = req.get_header_value("Authorization");
    if (bearer.rfind("Bearer ", 0) == 0 && same(bearer.substr(7), key)) return true;
    return same(cookie_value(req, "mgkey"), to_hex(key));
}

